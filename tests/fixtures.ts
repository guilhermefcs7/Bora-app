import type { Category, Destination, Place } from '../src/types';

// Dados de exemplo usados só nos testes. O app não embute destinos.
// [nome, categoria, lat, lng, minutos, preço 0-3, região, descrição]
type Row = [string, Category, number, number, number, 0 | 1 | 2 | 3, string, string];

const build = (id: string, name: string, country: string, lat: number, lng: number, rows: Row[]): Destination => ({
  id,
  name,
  country,
  lat,
  lng,
  places: rows.map(
    ([n, cat, la, ln, dur, price, area, desc], i): Place => ({
      id: `${id}-${i + 1}`,
      name: n,
      cat,
      lat: la,
      lng: ln,
      dur,
      price,
      area,
      desc,
    }),
  ),
});

